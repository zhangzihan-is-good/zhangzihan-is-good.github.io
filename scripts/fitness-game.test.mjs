import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const source=await fs.readFile(new URL('../dist/hobbies-fitness.js',import.meta.url),'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return fs.readFile(new URL('../hobbies-fitness.js', import.meta.url), 'utf8'); });
const {ROUND_MS,TARGET,judgeTiming,createRound,strikeRound,advanceRound,advanceFrame}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(judgeTiming(TARGET),'perfect');
assert.equal(judgeTiming(TARGET+.05),'good');
assert.equal(judgeTiming(.1),'miss');
const round=createRound();
advanceRound(round,round.cycleMs*TARGET);
assert.equal(strikeRound(round),'perfect');
assert.equal(round.score,100);
assert.equal(round.combo,1);
assert.equal(strikeRound(round),null,'a pass permits only one attempt');
assert.equal(round.score,100,'repeated inputs cannot build score');
advanceRound(round,round.cycleMs-round.cycleElapsed);
assert.equal(round.cycle,1);
advanceRound(round,round.cycleMs*TARGET);
assert.equal(strikeRound(round),'perfect');
assert.equal(round.score,205,'accurate consecutive beats build a combo');
advanceRound(round,round.cycleMs-round.cycleElapsed);
assert.equal(strikeRound(round),'miss');
assert.equal(round.combo,0,'early attempts break the combo');
advanceRound(round,ROUND_MS);
assert.equal(round.done,true);
assert.equal(round.elapsed,ROUND_MS);
assert.equal(strikeRound(round),null,'a finished round cannot be scored');
const idle=createRound();advanceRound(idle,ROUND_MS);
assert.ok(idle.miss>20,'unattempted beats count as misses');
assert.equal(idle.score,0);
const spam=createRound();
for(let elapsed=0;elapsed<ROUND_MS;elapsed+=10){strikeRound(spam);advanceRound(spam,10);}
assert.equal(spam.score,0,'spamming each new pass only hits early and never scores');
const before=JSON.stringify(idle);advanceRound(idle,-1);advanceRound(idle,NaN);assert.equal(JSON.stringify(idle),before);
const lowFps=createRound();
for(let frame=0;frame<160;frame++)advanceFrame(lowFps,250);
assert.equal(lowFps.elapsed,ROUND_MS,'a 4 fps display still completes a 40-second round in 40 active seconds');
assert.equal(lowFps.done,true);
const stalled=createRound();advanceFrame(stalled,250);
const preStall=JSON.stringify(stalled);
assert.equal(advanceFrame(stalled,2000).paused,true,'a long unseen rendering stall requests pause');
assert.equal(JSON.stringify(stalled),preStall,'a long stall does not consume time or unseen beats');
assert.equal(advanceFrame(stalled,250).paused,false);
assert.equal(stalled.elapsed,500,'resumed frames continue from the saved in-memory phase');
assert.doesNotMatch(source,/\b(?:localStorage|sessionStorage|document\.cookie)\b/);
console.log('Fitness game: judgment, combo, per-pass gating, missed beats, 40-second end, spam protection, low-FPS timing, and stall pause passed.');
